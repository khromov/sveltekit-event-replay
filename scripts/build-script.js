// Minifies src/script/capture.js into src/lib/generated/script.js, together with the CSP hash of
// the exact text that ends up inside the inline <script> tag.
import { transform } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

/** @returns {Promise<string>} the contents of the generated module */
export async function generate() {
	const source = readFileSync(`${root}/src/script/capture.js`, 'utf8');
	const { code } = await transform(source, { minify: true, target: 'es2020', charset: 'utf8' });
	const script = code.trim();

	if (/<\/script/i.test(script) || script.includes('<!--')) {
		throw new Error('The capture script must not contain </script or <!--');
	}

	const hash = `sha256-${createHash('sha256').update(script).digest('base64')}`;

	return `// Generated by scripts/build-script.js from src/script/capture.js — do not edit.

/** The minified inline script that captures events before hydration. */
export const SCRIPT = ${JSON.stringify(script)};

/**
 * CSP hash of {@link SCRIPT}. Add it to \`script-src\` if you use a Content Security Policy —
 * the value is the same for every app and every set of options.
 *
 * @example
 * \`\`\`js
 * csp: { directives: { 'script-src': ['self', SCRIPT_HASH] } }
 * \`\`\`
 */
export const SCRIPT_HASH = /** @type {const} */ (${JSON.stringify(hash)});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	mkdirSync(`${root}/src/lib/generated`, { recursive: true });
	writeFileSync(`${root}/src/lib/generated/script.js`, await generate());
	console.log('Generated src/lib/generated/script.js');
}
